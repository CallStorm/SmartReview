# -*- coding: utf-8 -*-
"""把首跑准确度分析导出为桌面 docx 报告（一次性脚本）。"""
from docx import Document
from docx.shared import Pt
from docx.oxml.ns import qn

doc = Document()
style = doc.styles["Normal"]
style.font.name = "Calibri"
style.font.size = Pt(11)
style.element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")

def h(text, level=1):
    doc.add_heading(text, level=level)

def p(text, bold=False):
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold = bold
    return para

def bullets(items):
    for it in items:
        doc.add_paragraph(it, style="List Bullet")

# ===== 封面 =====
doc.add_heading("SmartReview 内容审核「首次审核准确度」分析与改进方案", 0)
p("分析对象：用户 maoyu《悬挑脚手架》方案（线上最近 7 次审核 + 本地 3 次验证）")
p("分析日期：2026-08-16")
p("核心结论：逐项清单判定 + 结果缓存上线后，多次审核已可逐条复现；剩余短板集中在"
  "「第一次审核的漏检」。本文档给出四个根因与四层改进方案（L1-L4）。")

h("一、背景与已完成改造", 1)
bullets([
    "线上 7 次审核（任务 621-627）：每次只报出全部问题的一个随机子集（4/14/2/4/3/3/2 条），"
    "同一问题 severity 摇摆，622 出现 10 条违反全局规则的越权问题。",
    "已完成：内容审核改为逐项清单判定（检查项确定性拆分、每项必回填 verdict、清单外问题程序性丢弃、"
    "问题携带检查项溯源）；节点级结果缓存（同文档+同规则+同模型结果逐条一致）。",
    "本地验证：同文档两跑 31/31 内容节点 + 4/4 一致性节点命中缓存、结果完全一致；仅改一节时只有该节重新审核。",
])

h("二、为什么「第一次」仍会漏：四个根因", 1)

h("根因 1：检查项粒度太粗，漏检藏在「一项多点」里", 2)
p("现在一个检查项往往一句话塞了十几个检查点：")
bullets([
    "n17-2 架体技术参数：15 个参数（排数、钢管类型、架体高度、步距、纵距、横距、连墙件布置、"
    "主梁间距、连接方式、锚固点、锚环直径、悬挑长度、锚固长度、混凝土强度等）挤一项，"
    "漏掉「锚环直径」模型照样判通过。",
    "n2-1 工程概况 8 个要素一项；n24-1 监测 9 个要素一项；n33-1 验收 5 类验收内容一项。",
    "模型对一项只回填一个 verdict，子点缺失极易被「总体提到了」淹没——这是首跑漏检的最大来源。",
])

h("根因 2：判定规则有缺口——「占位文字算不算含有」", 2)
bullets([
    "n33 案例：正文写的是「列出扣件材质、外观、紧固力矩等验收要求」（对编写者的指示，不是验收内容本身）。",
    "按现行全局规则「存在性型：找到对应表述即通过」，判 pass 说得通；线上 627 判 error 也说得通——"
    "规则本身没定义这种情况，导致同类问题线上/本地判定不一致。",
])

h("根因 3：pass 不需要举证", 2)
bullets([
    "checks 格式里 verdict=pass 时 evidence 留空，模型可以「扫一眼觉得有」就 pass，"
    "没有被强制去正文里找到那段话——第二大漏检来源。",
])

h("根因 4：一致性比对点没有配置", 2)
p("4 个节点的上下文一致性提示词都只有一句话：")
tbl = doc.add_table(rows=1, cols=3)
tbl.style = "Light Grid Accent 1"
hdr = tbl.rows[0].cells
hdr[0].text = "节点"
hdr[1].text = "配置的比对要求"
hdr[2].text = "缺口"
rows = [
    ("n29 其他作业人员 ↔ n15 劳动力计划", "只比「其他人员数量」", "没配工种名称比对——「刷漆工/油漆工」不一致不在配置范围内"),
    ("n17 技术参数 ↔ n14 材料计划", "只比「规格型号与数量」", "未列具体字段清单"),
    ("n40 计算书 ↔ n17 技术参数", "「技术参数应一致」", "未列参数比对清单"),
    ("n28 特种作业 ↔ n15 劳动力计划", "只比「数量」", "未比工种、证书"),
]
for r in rows:
    cells = tbl.add_row().cells
    for i, v in enumerate(r):
        cells[i].text = v
p("线上 627 报出「刷漆工/油漆工」是模型超范围发挥（碰巧对了）；本地按配置判 0 条反而更符合"
  "「问题都必须与配置规则相关」。要让这类问题稳定首跑报出，必须把比对点配置出来。")
p("方向性结论：不要靠把全局规则写得更「凶」来提召回——622 的 10 条越权爆发就是这么来的。"
  "正确方向是把检查项拆得更细、更可判定，让规则更窄。", bold=True)

h("三、改进方案（四层，按投入产出排序）", 1)

h("L1 规则文本修订（零代码，立即生效）", 2)
p("全局规则《二、按检查项类型判定》补两条：")
bullets([
    "存在性型判通过的前提是能在正文引用到证明存在的原文；引用不到按未给出处理。",
    "正文出现「列出/应包括/详见/后附」等指示性措辞而实际内容未给出的，视为「未给出」（堵住占位文字缺口）。",
])

h("L2 检查项结构化拆分到「最小可判定单元」（核心工程，半自动）", 2)
bullets([
    "把检查项从「句」拆到「子项」：顿号/括号枚举逐个成项。如 n33 拆成 6 项，n17 的 15 个参数逐个成项。",
    "每项标注类型（存在/清单/量化）与通过判据，写进 item 文本，模型不再自行分类。",
    "落地方式：后端已支持节点级 check_items 显式配置；脚本自动预拆生成「管理员确认清单」，"
    "逐项勾选修订后回写模板；20+ 模板可批量执行。",
])

h("L3 管线：pass 举证（「引用即核查」）", 2)
bullets([
    "checks 输出对 pass 项也要求 evidence（正文引文 ≤50 字）。",
    "清单/量化型 pass 但引文缺失 -> 记 warning 日志（先观测，稳定后可升级为强制 fail 复核）。",
    "代价：每节点输出略增；换来模型必须真正定位到内容才能 pass。",
])

h("L4 一致性比对清单化（配置）", 2)
bullets([
    "4 个节点的比对提示词改为字段级清单，例如 n29：逐工种比对工种名称须与劳动力计划完全一致"
    "（如刷漆工/油漆工属同一工种须统一用词）、人数须一致。",
    "代码上 context 步骤复用 checks 机制（每条比对点一个 item_id），一并纳入缓存。",
])

h("L5（可选，暂缓）：首跑双采样", 2)
p("关键节点首跑同 prompt 调 2 次取并集，进一步压漏检；成本 ×2，有缓存后仅首跑付一次。"
  "建议做成配置开关，等 L1-L4 效果数据出来再定。")

h("四、实施顺序与验收标准", 1)
bullets([
    "实施顺序：L1 + L4（纯配置）→ L3（半天）→ L2（拆分脚本 + 管理员确认）。",
    "验收基准：以 maoyu 文档为基准集，线上 7 次审核的全部历史问题点并集（约 14 个）作为召回基准；"
    "改造后首跑应一次性报出其中所有「按规则该报」的项；同文档复跑结果逐条一致。",
])

doc.save(r"C:\Users\Administrator\Desktop\SmartReview首次审核准确度分析与改进方案.docx")
print("saved")
